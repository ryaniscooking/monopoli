// pnpm build:engine-edge - bundles packages/server (+ engine, maps, zod, supabase-js) into one ESM
// file for Supabase Edge Functions (Deno), and writes a tiny index.ts per function (spec 10.9).
// The engine is never imported from outside supabase/functions at runtime.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { FUNCTIONS } from '@monopoli/server';

const fnDir = join(import.meta.dirname, '..', 'supabase', 'functions');
const outfile = join(fnDir, '_shared', 'server.js');

const result = await build({
  entryPoints: [join(import.meta.dirname, '..', 'packages', 'server', 'src', 'deno.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  metafile: true,
  banner: { js: '// Generated by `pnpm build:engine-edge`. Do not edit.' },
});

for (const name of Object.keys(FUNCTIONS)) {
  mkdirSync(join(fnDir, name), { recursive: true });
  writeFileSync(
    join(fnDir, name, 'index.ts'),
    `// Generated by \`pnpm build:engine-edge\`. Do not edit.\nimport { serve } from '../_shared/server.js';\n\nserve('${name}');\n`,
  );
}

const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(
  `✓ ${outfile} (${(bytes / 1024).toFixed(0)} KB), ${Object.keys(FUNCTIONS).length} functions`,
);
